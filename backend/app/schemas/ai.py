from datetime import datetime, timezone
from typing import Optional, List
from pydantic import BaseModel, Field, field_validator


class ChatRequest(BaseModel):
    """Request model for local AI chat generation."""
    prompt: str = Field(
        ...,
        min_length=1,
        max_length=10000,
        description="The prompt or question to ask the local LLM."
    )
    system_prompt: Optional[str] = Field(
        None,
        max_length=2000,
        description="Optional instructions or persona for the model."
    )
    temperature: float = Field(
        default=0.7,
        ge=0.0,
        le=1.0,
        description="Sampling temperature for text diversity (0.0 to 1.0)."
    )
    max_tokens: Optional[int] = Field(
        None,
        ge=1,
        le=4096,
        description="Maximum number of tokens to predict."
    )

    @field_validator("prompt")
    @classmethod
    def validate_prompt(cls, v: str) -> str:
        clean = v.strip()
        if not clean:
            raise ValueError("Prompt must not be empty or contain only whitespace.")
        return clean


class ChatResponse(BaseModel):
    """Response model containing generated text and inference metadata."""
    response: str = Field(..., description="The response generated by the local LLM.")
    model: str = Field(..., description="The Ollama model used for generation.")
    duration_ms: Optional[float] = Field(None, description="Inference elapsed time in milliseconds.")
    eval_count: Optional[int] = Field(None, description="Number of tokens generated.")
    timestamp: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="UTC timestamp of the generation."
    )


class OllamaStatusResponse(BaseModel):
    """Status report for the local Ollama instance and models."""
    status: str = Field(..., description="'ready', 'model_missing', or 'offline'")
    server_reachable: bool = Field(..., description="Whether Ollama HTTP API responded.")
    model_installed: bool = Field(..., description="Whether the target model is pulled.")
    target_model: str = Field(..., description="Name of the configured model.")
    available_models: List[str] = Field(default_factory=list, description="List of locally installed models.")
    message: Optional[str] = Field(None, description="Actionable status or setup instruction.")
    timestamp: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="UTC timestamp of status check."
    )
